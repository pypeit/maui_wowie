"""
Script to run ``run_pypeit`` on a night of Keck/HIRES data, i.e. to perform
the main PypeIt reduction.

``run_pypeit`` is executed from within the data directory, using a PypeIt
file generated by :mod:`maui_wowie.pypeit.run_setup`.  The reduction
products (the ``Calibrations``, ``Science`` and ``QA`` folders) are written
to the folder holding the PypeIt file (e.g. ``keck_hires_orig_A``), via
``run_pypeit -r``.  By default the script processes
the UT 1997-05-09 observations of Q1645+5520.

Usage::

    conda run -n pypeit14 python -m maui_wowie.pypeit.run_reduce
"""
import os
import glob
import argparse

from pypeit.scripts.run_pypeit import RunPypeIt

from maui_wowie.pypeit.run_setup import DATA_DIR, SPECTROGRAPH


def get_parser():
    """
    Construct the command-line argument parser.

    Returns:
        `argparse.ArgumentParser`_: The parser.
    """
    parser = argparse.ArgumentParser(
        description='Run run_pypeit on a night of HIRES data.')
    parser.add_argument('--datadir', type=str, default=DATA_DIR,
                        help='Data directory for the night; run_pypeit is '
                             'executed from here.')
    parser.add_argument('--spectrograph', type=str, default=SPECTROGRAPH,
                        help='PypeIt spectrograph name.')
    parser.add_argument('--setup', type=str, default='A',
                        help='Configuration (setup) letter to reduce.')
    parser.add_argument('--calib_only', default=False, action='store_true',
                        help='Only process the calibrations.')
    parser.add_argument('--redo_calibs', default=False, action='store_true',
                        help='Do not reuse previously generated calibrations.')
    parser.add_argument('--no_overwrite', default=False, action='store_true',
                        help='Do not overwrite existing reduction products.')
    return parser


def main(args):
    """
    Run ``run_pypeit`` from within the data directory.

    Args:
        args (`argparse.Namespace`_):
            Parsed command-line arguments; see :func:`get_parser`.
    """
    # The PypeIt file, relative to the data directory; this follows the
    # naming convention of pypeit_setup
    name = f'{args.spectrograph}_{args.setup}'
    pypeit_file = os.path.join(name, f'{name}.pypeit')
    if not os.path.isfile(os.path.join(args.datadir, pypeit_file)):
        raise FileNotFoundError(
            f'No PypeIt file: {os.path.join(args.datadir, pypeit_file)}.  '
            'Run maui_wowie.pypeit.run_setup first.')

    # Build the equivalent of the run_pypeit command line
    command = [pypeit_file]
    # Write the reduction products next to the PypeIt file
    command += ['-r', os.path.join(args.datadir, name)]
    if not args.no_overwrite:
        command += ['-o']
    if args.calib_only:
        command += ['-c']
    if args.redo_calibs:
        command += ['-m']
    print(f'cd {args.datadir}')
    print('run_pypeit ' + ' '.join(command))

    # Remove existing spec1d files before overwriting them.  When a spec1d
    # file exists, PypeIt reads it back and keeps the objects of the
    # detectors not being reduced.  For keck_hires_orig the detector number
    # (rdx detnum = 1) never matches the DET entries in the file ('DET01'),
    # so the old objects are kept and every order appears twice.
    if not args.no_overwrite and not args.calib_only:
        science_dir = os.path.join(args.datadir, name, 'Science')
        old_files = sorted(glob.glob(os.path.join(science_dir, 'spec1d_*.fits'))
                           + glob.glob(os.path.join(science_dir, 'spec1d_*.txt')))
        for old_file in old_files:
            print(f'Removing {old_file}')
            os.remove(old_file)

    # run_pypeit writes its output to the current working directory
    cwd = os.getcwd()
    os.chdir(args.datadir)
    try:
        RunPypeIt.main(RunPypeIt.parse_args(command))
    finally:
        # Always return to where we started
        os.chdir(cwd)


if __name__ == '__main__':
    main(get_parser().parse_args())
